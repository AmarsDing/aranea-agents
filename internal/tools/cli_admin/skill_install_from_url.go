package cli_admin

import (
	"context"
	"fmt"

	"aranea-agents/internal/pkginstall"
	"aranea-agents/pkg/apierror"
	trpctool "trpc.group/trpc-go/trpc-agent-go/tool"
	"trpc.group/trpc-go/trpc-agent-go/tool/function"
)

type skillInstallInput struct {
	URL      string `json:"url" jsonschema:"description=Skill Git 仓库 URL,required"`
	Ref      string `json:"ref" jsonschema:"description=分支或 Tag（默认使用仓库默认分支）"`
	Subpath  string `json:"subpath" jsonschema:"description=子目录路径"`
	Decision string `json:"decision" jsonschema:"description=Conflict resolution strategy: skip (keep existing, skip new), keep (overwrite existing with new), refine (merge new into existing)"`
}

type skillInstallOutput struct {
	Created   int      `json:"created"`
	Updated   int      `json:"updated"`
	Skipped   int      `json:"skipped"`
	Errors    []string `json:"errors,omitempty"`
	Steps     []string `json:"steps"`
	JobID     string   `json:"job_id,omitempty"`
	Status    string   `json:"status,omitempty"` // installed|pending_conflict|failed
	Conflicts []pkginstall.ConflictInfo `json:"conflicts,omitempty"`
}

func newSkillInstallFromURLTool(deps Deps) trpctool.Tool {
	execute := func(ctx context.Context, input skillInstallInput) (skillInstallOutput, error) {
		if input.URL == "" {
			return skillInstallOutput{}, apierror.BadRequest(apierror.DomainTool, "url is required")
		}
		if err := validateRepoURL(input.URL, deps.AllowedPrivateHosts); err != nil {
			return skillInstallOutput{}, err
		}
		manifest := &pkginstall.Manifest{
			Version: 1,
			Metadata: pkginstall.ManifestMetadata{
				Name:        "single-skill-install",
				Description: "single skill install generated by cli_admin_skill_install_from_url",
			},
			Spec: pkginstall.ManifestSpec{
				Skills: []pkginstall.SkillSpec{{
					URL:      input.URL,
					Ref:      input.Ref,
					Subpath:  input.Subpath,
					Decision: input.Decision,
				}},
			},
		}
		if err := pkginstall.ValidateManifest(manifest); err != nil {
			return skillInstallOutput{}, apierror.BadRequest(apierror.DomainTool, "invalid skill install manifest: %v", err)
		}

		var stepLog []string
		ins := &pkginstall.Installer{
			APIURL: deps.APIBaseURL,
			Token:  deps.APIToken,
			Quiet:  true,
			OnStep: func(step, total int, name, status string) {
				stepLog = append(stepLog, fmt.Sprintf("[%d/%d] %s: %s", step, total, name, status))
			},
		}
		result, err := ins.Install("", manifest)
		if err != nil {
			return skillInstallOutput{}, apierror.Internal(apierror.DomainTool, "install skill: %v", err)
		}
		for _, sr := range result.Steps {
			stepLog = append(stepLog, fmt.Sprintf("%s %s %s", sr.Resource, sr.Action, sr.Message))
		}
		jobID, status, conflicts := summarizeSkillSteps(result.Steps)
		return skillInstallOutput{
			Created:   result.Created,
			Updated:   result.Updated,
			Skipped:   result.Skipped,
			Errors:    result.Errors,
			Steps:     stepLog,
			JobID:     jobID,
			Status:    status,
			Conflicts: conflicts,
		}, nil
	}
	return function.NewFunctionTool(
		execute,
		function.WithName("cli_admin_skill_install_from_url"),
		function.WithDescription("从 Git 仓库 URL 安装 Skill。返回三态结果：installed=已安装；pending_conflict=检测到重复/相似 Skill，需用户决策后用 decision 参数重试（skip=保留现有跳过新包；keep=用新包覆盖现有；refine=AI 融合），此时 conflicts 字段列出冲突组（group_id/相似度/已有 skill slug）；failed=失败。使用 subpath 指定仓库中的 Skill 子目录。"),
	)
}
