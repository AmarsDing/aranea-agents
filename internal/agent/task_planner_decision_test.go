// TestEmitPlannerDecision_DecisionKeyUnique guards against accidental key
// reuse across emissions (uniqueness is the insert-or-ignore dedup anchor).
func TestEmitPlannerDecision_DecisionKeyUnique(t *testing.T) {
	cc := &captureDecisionCollector{}
	impl := &taskPlannerImpl{lg: loggateway.NewNoop(), decisions: cc}
	d := plannerDecision{TraceID: "tr-4", Mode: "direct", Strategy: biz.StrategyDirect}

	impl.emitPlannerDecision(context.Background(), d)
	impl.emitPlannerDecision(context.Background(), d)

	if len(cc.recs) != 2 {
		t.Fatalf("expected 2 records, got %d", len(cc.recs))
	}
	if cc.recs[0].DecisionKey == cc.recs[1].DecisionKey {
		t.Error("decision_key must be unique per emission")
	}
}

// TestAttachPlannerDecisionCollector verifies the wire-time attach helper
// reaches the concrete impl (Attach* precedent: AttachPlannerOrganizationReader).
func TestAttachPlannerDecisionCollector(t *testing.T) {
	var p biz.TaskPlannerPort = &taskPlannerImpl{lg: loggateway.NewNoop()}
	cc := &captureDecisionCollector{}
	AttachPlannerDecisionCollector(p, cc)

	impl := p.(*taskPlannerImpl)
	impl.emitPlannerDecision(context.Background(), plannerDecision{
		TraceID: "tr-5", Mode: "dag", Strategy: biz.StrategyDAG,
	})
	if len(cc.recs) != 1 {
		t.Fatalf("attach helper did not wire the collector: %d records", len(cc.recs))
	}
}

// TestEmitTeamCountMismatchGate_Truncate pins the M80 1.6 G-R4 truncate branch
// (design §3.2 row 3): outcome=truncated, observed=decomposed, threshold=
// requested, dropped names land in metadata.
func TestEmitTeamCountMismatchGate_Truncate(t *testing.T) {
	cc := &captureDecisionCollector{}
	impl := &taskPlannerImpl{lg: loggateway.NewNoop(), decisions: cc}

	impl.emitTeamCountMismatchGate(context.Background(), "tr-6", "ss-6", "truncate", 2, 4, []string{"Team C", "Team D"})

	if len(cc.recs) != 1 {
		t.Fatalf("expected 1 record, got %d", len(cc.recs))
	}
	r := cc.recs[0]
	if r.Category != decision.CategorySystemGuard {
		t.Errorf("category = %q, want system_guard", r.Category)
	}
	if r.Outcome != "truncated" {
		t.Errorf("outcome = %q, want truncated", r.Outcome)
	}
	if r.ActorKey != "system:plan_verifier" {
		t.Errorf("actor_key = %q, want system:plan_verifier", r.ActorKey)
	}
	if r.SourceRef.FlowTraceID != "tr-6" {
		t.Errorf("source_ref.flow_trace_id = %q, want tr-6", r.SourceRef.FlowTraceID)
	}
	if got := r.Metadata["trigger_rule"]; got != decision.TriggerTeamCountMismatch {
		t.Errorf("metadata.trigger_rule = %v", got)
	}
	if got := r.Metadata["observed_value"]; got != 4 {
		t.Errorf("metadata.observed_value = %v, want 4", got)
	}
	if got := r.Metadata["threshold"]; got != 2 {
		t.Errorf("metadata.threshold = %v, want 2", got)
	}
	if got := r.Metadata["action"]; got != "truncate" {
		t.Errorf("metadata.action = %v", got)
	}
	if got, ok := r.Metadata["dropped_subtask_names"].([]string); !ok || len(got) != 2 {
		t.Errorf("metadata.dropped_subtask_names = %v", r.Metadata["dropped_subtask_names"])
	}
	if err := r.Validate(); err != nil {
		t.Errorf("emitted record must pass validation: %v", err)
	}
}

