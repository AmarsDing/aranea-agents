// captureDecisionCollector is the test double for decision.Collector.
type captureDecisionCollector struct {
	recs []decision.Record
}

func (c *captureDecisionCollector) Emit(_ context.Context, r decision.Record) {
	c.recs = append(c.recs, r)
}

// TestEmitPlannerDecision_DecisionRecordMapping pins the M80 1.4 adapter
// contract (design §3.2 row 1): the FlowLog emit path double-writes one
// planner_orchestration record with the exact field mapping.
func TestEmitPlannerDecision_DecisionRecordMapping(t *testing.T) {
	cc := &captureDecisionCollector{}
	impl := &taskPlannerImpl{lg: loggateway.NewNoop(), decisions: cc}

	impl.emitPlannerDecision(context.Background(), plannerDecision{
		TraceID:         "tr-1",
		DecisionSource:  "llm_mode",
		Mode:            "parallel",
		Strategy:        biz.StrategyParallel,
		ComplexityLevel: biz.ComplexityComplex,
		ComplexityScore: 0.82,
		TeamCount:       3,
		KeywordFallback: false,
		StrategyReason:  "LLM 指定 parallel 模式",
		SpiritSessionID: "ss-1",
	})

	if len(cc.recs) != 1 {
		t.Fatalf("expected 1 decision record, got %d", len(cc.recs))
	}
	r := cc.recs[0]
	if r.DecisionKey == "" {
		t.Error("decision_key must be generated by the adapter")
	}
	if r.Category != decision.CategoryPlannerOrchestration {
		t.Errorf("category = %q, want %q", r.Category, decision.CategoryPlannerOrchestration)
	}
	if want := "策略路由: parallel/parallel"; r.Scenario != want {
		t.Errorf("scenario = %q, want %q", r.Scenario, want)
	}
	if r.Reasoning != "LLM 指定 parallel 模式" {
		t.Errorf("reasoning = %q", r.Reasoning)
	}
	if r.Outcome != "selected_parallel" {
		t.Errorf("outcome = %q, want selected_parallel", r.Outcome)
	}
	if r.Confidence == nil || *r.Confidence != 0.82 {
		t.Errorf("confidence = %v, want 0.82", r.Confidence)
	}
	if r.ActorType != decision.ActorSystem {
		t.Errorf("actor_type = %q, want system", r.ActorType)
	}
	if r.ActorKey == "" {
		t.Error("actor_key must be set (validation requires non-empty)")
	}
	if r.SourceRef.FlowTraceID != "tr-1" {
		t.Errorf("source_ref.flow_trace_id = %q, want tr-1", r.SourceRef.FlowTraceID)
	}
	if got := r.Metadata["decision_source"]; got != "llm_mode" {
		t.Errorf("metadata.decision_source = %v", got)
	}
	if got := r.Metadata["fallback_triggered"]; got != false {
		t.Errorf("metadata.fallback_triggered = %v", got)
	}
	if got := r.Metadata["team_count"]; got != 3 {
		t.Errorf("metadata.team_count = %v", got)
	}
	if got := r.Metadata["spirit_session_id"]; got != "ss-1" {
		t.Errorf("metadata.spirit_session_id = %v", got)
	}
}

