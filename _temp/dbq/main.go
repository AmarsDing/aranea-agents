package main

import (
	"database/sql"
	"fmt"
	"os"

	_ "github.com/lib/pq"
)

// Pre-fix probe for P0-1 (jsonb_set on TEXT column).
// Verifies on the real Postgres instance:
//   P1: current JSONSet output fails with 42883 (reproduces run.persist_failed)
//   P2: current JSONRemove output on a bare text column fails (operator text - text)
//   P3: proposed JSONBBase-wrapped JSONSet works, incl. '' empty-string edge
//   P4: proposed chain jsonb_set(...) - key works, jsonb→text assignment cast OK
//   P5: NULL column edge handled by COALESCE guard
func main() {
	dsn := "postgres://postgres:Hangshan%40123@127.0.0.1:5432/aranea?sslmode=disable"
	db, err := sql.Open("postgres", dsn)
	if err != nil {
		fmt.Println("open err:", err)
		os.Exit(1)
	}
	defer db.Close()
	db.SetMaxOpenConns(1) // keep one session so the TEMP table persists across statements
	if err := db.Ping(); err != nil {
		fmt.Println("ping err:", err)
		os.Exit(1)
	}

	exec := func(label, q string, args ...any) {
		_, err := db.Exec(q, args...)
		if err != nil {
			fmt.Printf("%s: ERROR: %v\n", label, err)
			return
		}
		fmt.Printf("%s: OK\n", label)
	}
	show := func(label, q string, args ...any) {
		rows, err := db.Query(q, args...)
		if err != nil {
			fmt.Printf("%s: QUERY ERROR: %v\n", label, err)
			return
		}
		defer rows.Close()
		for rows.Next() {
			var id, j string
			var jn sql.NullString
			if err := rows.Scan(&id, &jn); err != nil {
				fmt.Printf("%s: SCAN ERROR: %v\n", label, err)
				return
			}
			j = jn.String
			if !jn.Valid {
				j = "<NULL>"
			}
			fmt.Printf("%s: id=%s j=%s\n", label, id, j)
		}
	}

	exec("setup", `CREATE TEMP TABLE t_probe(id text PRIMARY KEY, j text)`)
	exec("seed", `INSERT INTO t_probe(id, j) VALUES ('r1','{}'), ('r2',''), ('r3','{"a":"1"}'), ('r4',NULL)`)

	// P1: exact SQL shape currently generated by Dialect.JSONSet (Postgres branch)
	exec("P1 current JSONSet (expect 42883)",
		`UPDATE t_probe SET j = jsonb_set(j, '{run_status}', to_jsonb($1::text)) WHERE id = 'r1'`, "running")

	// P2: exact SQL shape currently generated by Dialect.JSONRemove on bare column
	exec("P2 current JSONRemove bare col (expect operator error)",
		`UPDATE t_probe SET j = j - $1::text WHERE id = 'r1'`, "run_id")

	// P3: proposed fix — JSONBBase-wrapped column
	exec("P3 proposed JSONBBase+JSONSet r1/r2",
		`UPDATE t_probe SET j = jsonb_set(COALESCE(NULLIF(j,'')::jsonb,'{}'::jsonb), '{run_status}', to_jsonb($1::text)) WHERE id IN ('r1','r2')`, "running")
	show("P3 result", `SELECT id, j FROM t_probe WHERE id IN ('r1','r2') ORDER BY id`)

	// P4: proposed chain — JSONSet then JSONRemove on jsonb expr, assign back to text col
	exec("P4 proposed chain set+remove r3",
		`UPDATE t_probe SET j = jsonb_set(COALESCE(NULLIF(j,'')::jsonb,'{}'::jsonb), '{b}', to_jsonb($1::text)) - $2::text WHERE id = 'r3'`, "x", "a")
	show("P4 result", `SELECT id, j FROM t_probe WHERE id = 'r3'`)

	// P5: NULL edge
	exec("P5 proposed NULL edge r4",
		`UPDATE t_probe SET j = jsonb_set(COALESCE(NULLIF(j,'')::jsonb,'{}'::jsonb), '{b}', to_jsonb($1::text)) WHERE id = 'r4'`, "y")
	show("P5 result", `SELECT id, j FROM t_probe WHERE id = 'r4'`)

	exec("cleanup", `DROP TABLE t_probe`)
}
